"""Generate Recordings (mp3) for every Phrase with Piper, plus the data/audio.js manifest.

Usage (from the repository root, inside a virtualenv with tools/requirements.txt installed):

    python tools/generate_audio.py --voices-dir <dir with the .onnx voice files>

Only Phrases whose text, speaker or voice changed since the last run are re-recorded.
Requires ffmpeg on PATH for the wav -> mp3 conversion.
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

from piper import PiperVoice, SynthesisConfig

ROOT = Path(__file__).resolve().parent.parent
LESSONS = ROOT / "data" / "lessons.js"
MANIFEST = ROOT / "data" / "audio.js"
AUDIO_DIR = ROOT / "audio"
MANIFEST_PREFIX = "window.AUDIO = "

# speaker -> (Piper voice, speaker id inside a multi-speaker voice)
VOICES = {
    "m": ("es_ES-sharvard-medium", 0),  # sharvard speaker 0 = "M"
    "f": ("es_ES-sharvard-medium", 1),  # sharvard speaker 1 = "F"
}

PHRASE_RE = re.compile(
    r"\{\s*id:\s*'(?P<id>[^']+)',\s*speaker:\s*'(?P<speaker>[mf])',\s*es:\s*'(?P<es>(?:[^'\\]|\\.)*)'"
)


def read_phrases():
    text = LESSONS.read_text(encoding="utf-8")
    phrases = [m.groupdict() for m in PHRASE_RE.finditer(text)]
    expected = text.count("{ id: '")
    if len(phrases) != expected:
        sys.exit(f"Parsed {len(phrases)} phrases but lessons.js has {expected}; check the phrase format.")
    for p in phrases:
        p["es"] = p["es"].replace("\\'", "'")
    return phrases


def read_manifest():
    if not MANIFEST.exists():
        return {}
    body = MANIFEST.read_text(encoding="utf-8").split(MANIFEST_PREFIX, 1)[1].rstrip().rstrip(";")
    return json.loads(body)


def write_manifest(entries):
    header = (
        "// Generated by tools/generate_audio.py: do not edit by hand.\n"
        "// Phrase id -> Recording. The app plays a Recording only if its text matches the Phrase.\n"
    )
    body = json.dumps(entries, ensure_ascii=False, indent=2, sort_keys=True)
    MANIFEST.write_text(header + MANIFEST_PREFIX + body + ";\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--voices-dir", required=True, type=Path)
    parser.add_argument("--force", action="store_true", help="re-record every Phrase")
    args = parser.parse_args()

    if not shutil.which("ffmpeg"):
        sys.exit("ffmpeg is not on PATH.")

    phrases = read_phrases()
    old = read_manifest()
    AUDIO_DIR.mkdir(exist_ok=True)
    loaded = {}
    entries = {}
    made = 0

    for p in phrases:
        voice_name, speaker_id = VOICES[p["speaker"]]
        file = f"audio/{p['id']}.mp3"
        entry = {"text": p["es"], "voice": voice_name, "voiceSpeakerId": speaker_id, "speaker": p["speaker"], "file": file}
        entries[p["id"]] = entry
        if not args.force and old.get(p["id"]) == entry and (ROOT / file).exists():
            continue

        if voice_name not in loaded:
            model = args.voices_dir / f"{voice_name}.onnx"
            if not model.exists():
                sys.exit(f"Missing voice model {model}. See README, 'Recordings'.")
            loaded[voice_name] = PiperVoice.load(str(model))
        voice = loaded[voice_name]

        with tempfile.TemporaryDirectory() as tmp:
            wav_path = Path(tmp) / "phrase.wav"
            with wave.open(str(wav_path), "wb") as wav:
                voice.synthesize_wav(p["es"], wav, syn_config=SynthesisConfig(speaker_id=speaker_id))
            subprocess.run(
                ["ffmpeg", "-loglevel", "error", "-y", "-i", str(wav_path),
                 "-codec:a", "libmp3lame", "-q:a", "5", str(ROOT / file)],
                check=True,
            )
        made += 1
        print(f"recorded {p['id']} ({voice_name}): {p['es']}")

    # Drop Recordings of Phrases that no longer exist.
    keep = {Path(e["file"]).name for e in entries.values()}
    for f in AUDIO_DIR.glob("*.mp3"):
        if f.name not in keep:
            f.unlink()
            print(f"removed {f.name}")

    write_manifest(entries)
    print(f"{made} recorded, {len(entries) - made} unchanged.")


if __name__ == "__main__":
    main()
